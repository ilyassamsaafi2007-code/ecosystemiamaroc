def tr(key, lang="fr", **kw):
    row = T.get(key)
    if row is None:
        return key
    idx = LANGS.index(lang) if lang in LANGS else 0
    text = row[idx] or row[0]
    try:
        return text.format(**kw) if kw else text
    except (KeyError, IndexError):
        return text
